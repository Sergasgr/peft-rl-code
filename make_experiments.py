"""Write experiments/ and queue.txt from methods.json.

    uv run python make_experiments.py

Three stages per method, each unlocked by editing methods.json and running this again:
1. LR grid with the `tests` reward, seed 0                                  → always
2. the selected LR with the `tests+quality` and `quality` rewards           → once `selected_lr` is set
3. extra seeds of the selected LR, `tests` and `tests+quality` rewards     → once `extra_seeds` is set
Plus the pilot (0.5B model, LoRA, all three rewards), which goes first in the queue.
Existing folders are rewritten with the same content; results are never touched.
"""

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def lr_tag(lr: float) -> str:
    """1e-05 → 1e-5, 4.5e-03 → 4.5e-3"""
    mantissa, exponent = f"{lr:e}".split("e")
    return f"{mantissa.rstrip('0').rstrip('.')}e{int(exponent)}"


def write(exp_dir: Path, adapter: Path | None, params: dict) -> Path:
    exp_dir.mkdir(parents=True, exist_ok=True)
    if adapter:
        shutil.copyfile(adapter, exp_dir / "adapter_config.json")
    (exp_dir / "training_params.json").write_text(json.dumps(params, indent=2) + "\n", encoding="utf-8")
    return exp_dir


def main(root: Path = ROOT) -> list[str]:
    spec = json.loads((root / "methods.json").read_text(encoding="utf-8"))
    experiments = root / "experiments"
    stages: list[list[Path]] = [[], [], [], []]

    pilot = spec["pilot"]
    adapter = root / spec["methods"][pilot["method"]]["adapter"]
    for reward in pilot["rewards"]:
        stages[0].append(
            write(
                experiments / "pilot" / f"{pilot['method']}-lr{lr_tag(pilot['learning_rate'])}-{reward}",
                adapter,
                {"model_id": pilot["model_id"], "learning_rate": pilot["learning_rate"], "reward": reward},
            )
        )

    for method, m in spec["methods"].items():
        extra = m.get("training_params", {})
        adapter = root / m["adapter"] if m["adapter"] else None
        for lr in m["grid"]:
            stages[1].append(
                write(
                    experiments / method / f"lr{lr_tag(lr)}-tests",
                    adapter,
                    {**extra, "learning_rate": lr, "reward": "tests"},
                )
            )
        lr = m["selected_lr"]
        if lr is None:
            continue
        for reward in ("tests+quality", "quality"):
            stages[2].append(
                write(
                    experiments / method / f"lr{lr_tag(lr)}-{reward}",
                    adapter,
                    {**extra, "learning_rate": lr, "reward": reward},
                )
            )
        for seed in m["extra_seeds"]:
            for reward in ("tests", "tests+quality"):
                stages[3].append(
                    write(
                        experiments / method / f"lr{lr_tag(lr)}-{reward}-seed{seed}",
                        adapter,
                        {**extra, "learning_rate": lr, "reward": reward, "seed": seed},
                    )
                )

    lines = [str(p.relative_to(root)) for stage in stages for p in stage]
    (root / "queue.txt").write_text(
        "# Generated by make_experiments.py, in run order. Edit freely.\n" + "\n".join(lines) + "\n", encoding="utf-8"
    )
    print(f"{len(lines)} experiments ({', '.join(str(len(s)) for s in stages)} per stage) → queue.txt")
    return lines


if __name__ == "__main__":
    main()
