"""Summarize results/*.json into RESULTS.md.

    uv run python table.py

Table 1 picks each method's learning rate: the best KodCode-valid pass@1 with the `tests` reward, seed 0
(ties go to the lower rate). It never looks at test numbers. Table 2 has every run's test-side numbers.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def fmt(value, pct: bool = False, digits: int = 2) -> str:
    if value is None:
        return "—"
    return f"{100 * value:.1f}" if pct else f"{value:.{digits}f}"


def load(root: Path) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((root / "results").glob("*.json"))]


def lr_table(results: list[dict]) -> list[str]:
    grid = [
        r
        for r in results
        if r["run_info"]["params"].get("reward") == "tests"
        and r["run_info"]["params"].get("seed") == 0
        and not r["run_info"]["experiment_name"].startswith("pilot/")
        and not r["run_info"]["experiment_name"].startswith("baseline/")
    ]
    best: dict[str, tuple] = {}
    for r in grid:
        method = r["run_info"]["experiment_name"].split("/")[0]
        key = (r["eval"]["kodcode_valid"]["pass@1"], -r["run_info"]["params"]["learning_rate"])
        if method not in best or key > best[method][0]:
            best[method] = (key, r["run_info"]["params"]["learning_rate"])
    lines = ["| method | lr | valid pass@1 | selected |", "|---|---|---|---|"]
    for r in sorted(
        grid, key=lambda r: (r["run_info"]["experiment_name"].split("/")[0], r["run_info"]["params"]["learning_rate"])
    ):
        method, lr = r["run_info"]["experiment_name"].split("/")[0], r["run_info"]["params"]["learning_rate"]
        lines.append(
            f"| {method} | {lr:g} | {fmt(r['eval']['kodcode_valid']['pass@1'], True)} | "
            f"{'✓' if best[method][1] == lr else ''} |"
        )
    return lines


def runs_table(results: list[dict]) -> list[str]:
    header = (
        "| run | KodCode pass@1 | clean | HE+ | MBPP+ | quality | pylint | MI | no-op | lines | forgetting Δ | "
        "trainable | peak GB | train h |"
    )
    lines = [header, "|" + "---|" * (header.count("|") - 1)]
    for r in results:
        e = r.get("eval", {})
        name = r["run_info"]["experiment_name"]
        lines.append(row(name, e.get("kodcode_test", {}), e, r))
        for key in sorted(k for k in e if k.startswith("kodcode_test_best_of_")):  # baselines only
            lines.append(row(f"{name}, best-of-{key.rsplit('_', 1)[1]}", e[key], {}, {}))
    return lines


def row(name: str, test: dict, e: dict, r: dict) -> str:
    t = r.get("train_info", {})
    passing = test.get("passing", {})
    mem, train = t.get("accelerator_memory_max"), t.get("train_time")
    cells = [
        f"| {name}",
        fmt(test.get("pass@1"), True),
        fmt(test.get("clean_pass@1"), True),
        fmt(e.get("humaneval", {}).get("pass@1"), True),
        fmt(e.get("mbpp", {}).get("pass@1"), True),
        fmt(passing.get("quality")),
        fmt(passing.get("pylint")),
        fmt(passing.get("mi"), digits=1),
        fmt(test.get("noop_rate"), True),
        fmt(passing.get("code_lines"), digits=1),
        fmt(r.get("forgetting", {}).get("delta"), digits=3),
        f"{t['num_trainable_params']:,}" if t.get("num_trainable_params") else "—",
        fmt(mem / 1024**3 if mem else None, digits=1),
        fmt(train / 3600 if train else None, digits=1),
    ]
    return " | ".join(cells) + " |"


def main(root: Path = ROOT) -> None:
    results = load(root)
    text = "\n".join(
        [
            "# Results",
            "",
            "Generated by `table.py` from `results/*.json`. Percentages; KodCode = held-out test split (500 tasks);",
            "quality, pylint, MI and lines are means over passing solutions; HE+/MBPP+ = EvalPlus base + plus tests.",
            "",
            "## Learning rate per method (tests reward, seed 0, chosen on KodCode valid)",
            "",
            *lr_table(results),
            "",
            "## All runs",
            "",
            *runs_table(results),
            "",
        ]
    )
    (root / "RESULTS.md").write_text(text, encoding="utf-8")
    print(f"{len(results)} results → RESULTS.md")


if __name__ == "__main__":
    main()
